import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import {
  cpSync,
  mkdtempSync,
  mkdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "../src/compiler.mjs";

const root = fileURLToPath(new URL("../", import.meta.url));
const dir = mkdtempSync(join(tmpdir(), "threec-roundtrip-"));
const run = (exe, args) =>
  execFileSync(exe, args, {
    cwd: root,
    encoding: "utf8",
    timeout: 120000,
  }).trim();
function generate(classPath, main, es, js) {
  run("bash", [
    "-c",
    'source scripts/tool-env.sh && haxe -cp "$1" -main "$2" -D "js-es=$3" --js "$4"',
    "threec",
    classPath,
    main,
    String(es),
    js,
  ]);
}
function compareTargets(input, name, expected) {
  const original = run(process.execPath, [input]);
  if (expected !== undefined) assert.equal(original, expected);
  const portable = join(dir, name + "-haxe");
  run(process.execPath, ["src/cli.mjs", "emit", input, "--out", portable]);
  rmSync(input); // Backends receive only the generated Haxe project.
  for (const target of ["js", "c"]) {
    const output = join(dir, name + "-" + target);
    run(process.execPath, [
      "src/cli.mjs",
      "target",
      portable,
      "--target",
      target,
      "--out",
      output,
    ]);
    const result =
      target === "js"
        ? run(process.execPath, [join(output, "js/program.js")])
        : run(join(output, "c/Sample"), []);
    assert.equal(result, original, name + " on " + target);
  }
  console.log(
    name + " → Haxe → JS / C matched: " + original.replaceAll("\n", ", "),
  );
}
try {
  const fixture = join(dir, "source");
  mkdirSync(fixture);
  cpSync(
    join(root, "tests/fixtures/haxe-js/Projection.hx"),
    join(fixture, "Projection.hx"),
  );
  for (const es of [5, 6])
    generate(fixture, "Projection", es, join(dir, "es" + es + ".js"));
  rmSync(fixture, { recursive: true });
  for (const es of [5, 6])
    compareTargets(join(dir, "es" + es + ".js"), "es" + es, "30.625");

  for (const type of ["Int", "Float"]) {
    const path = join(dir, type);
    mkdirSync(path);
    writeFileSync(
      join(path, "Erased.hx"),
      "class Erased {static function twice(x:" +
        type +
        "):" +
        type +
        " return x+x; static function main() js.Browser.console.log(twice(3));}",
    );
    generate(path, "Erased", 6, join(path, "out.js"));
  }
  assert.deepEqual(
    readFileSync(join(dir, "Int/out.js")),
    readFileSync(join(dir, "Float/out.js")),
  );
  console.log("Int and Float signatures generated byte-identical JavaScript");

  // Regular hand-written JS, including the random-number recurrence used by Nácar.
  const authored = join(dir, "numeric.js");
  writeFileSync(
    authored,
    `
    class Random {
      static step(seed) { return (Math.imul(seed, 1664525) + 1013904223) >>> 0; }
    }
    let seed = 473817;
    for (let i=0; i<4; ++i) { seed = Random.step(seed); console.log(seed); }
    console.log(-1 >>> 0); console.log(-1 >>> 33); console.log(4294967295.9 | 0);
    console.log(Math.imul(-1, 4294967295)); console.log(Math.imul(4294967297, -2147483648));
  `,
  );
  compareTargets(authored, "javascript");
  assert.throws(
    () =>
      compile(
        "bad.js",
        '(function(root){"use strict";root.console.log(1);})(sideEffect());',
      ),
    /E-SUBSET/,
  );
  assert.throws(
    () =>
      compile(
        "bad.js",
        "function f(){ if (true) {var v=2;} console.log(v); } f();",
      ),
    /E-SUBSET/,
  );
} finally {
  rmSync(dir, { recursive: true, force: true });
}
